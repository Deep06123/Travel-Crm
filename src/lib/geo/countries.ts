const BY_NAME = new Map(COUNTRIES.map((country) => [country.name, country]));

/** The country stored on a booking, or `undefined` for a blank or stale name. */
export function findCountryByName(name: string | undefined): Country | undefined {
  return name ? BY_NAME.get(name) : undefined;
}

/** Subdivisions to offer for a stored country name; empty means free text. */
export function subdivisionsForCountry(name: string | undefined): string[] {
  return findCountryByName(name)?.subdivisions ?? [];
}
