/**
 * Countries and their first-level subdivisions, for address pickers.
 *
 * Names rather than ISO codes are stored on the booking: the billing columns
 * are free text (`optionalText(100)`), existing rows already hold typed names,
 * and the value is read by agents and printed on paperwork — a code would mean
 * a lookup at every read and would break the bookings already in the database.
 *
 * Subdivisions are only listed for the countries where an address is normally
 * written with one. Everywhere else `subdivisions` is empty and the caller
 * falls back to a free-text State field, which is the honest representation of
 * a country whose addresses have no state line.
 */

export type Country = {
  /** ISO 3166-1 alpha-2, used as the option key — never stored. */
  code: string;
  name: string;
  /** First-level subdivisions, or `[]` when addresses there have none. */
  subdivisions: string[];
};

